#!/usr/bin/env python
"""
ClaimWise SG - Load & Elasticity Evaluation Runner
Corresponds to Section 4.3 (Performance and Elasticity: Locust Stress Tests) of Preliminary.pdf.
Runs Locust in headless mode, collects latency & throughput percentiles,
verifies target (P95 < 250ms, error rate < 1%), and generates LaTeX evaluation tables.
"""

import os
import sys
import subprocess
import csv
import glob

EVAL_DIR = os.path.join(os.path.dirname(__file__), "../evaluation")
LOCUSTFILE = os.path.join(os.path.dirname(__file__), "../tests/load/locustfile.py")
CSV_PREFIX = os.path.join(EVAL_DIR, "locust_results")
OUTPUT_TEX = os.path.join(EVAL_DIR, "performance_results.tex")

def run_locust(host="http://localhost:3000", users=50, spawn_rate=10, run_time="12s"):
    os.makedirs(EVAL_DIR, exist_ok=True)

    # Clean previous csv files
    for f in glob.glob(f"{CSV_PREFIX}*"):
        try:
            os.remove(f)
        except OSError:
            pass

    cmd = [
        "/Users/frank/.local/bin/uv", "run", "--with", "locust", "locust",
        "-f", LOCUSTFILE,
        "--host", host,
        "--headless",
        "-u", str(users),
        "-r", str(spawn_rate),
        "-t", run_time,
        "--csv", CSV_PREFIX,
        "--only-summary"
    ]

    print(f"Running Locust: {users} users, spawn rate {spawn_rate}/s, duration {run_time}...")
    proc = subprocess.run(cmd, capture_output=True, text=True)

    if proc.returncode != 0 and "KeyboardInterrupt" not in proc.stderr:
        print("Locust stderr:", proc.stderr)

    # Parse results from stats CSV
    stats_file = f"{CSV_PREFIX}_stats.csv"
    if not os.path.exists(stats_file):
        print(f"Error: Stats file {stats_file} not found.")
        return None

    stats = []
    with open(stats_file, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            stats.append(row)

    return stats

def process_results(stats):
    if not stats:
        return

    print("\n=== Locust Load Test Summary (Section 4.3) ===")
    total_row = None
    for row in stats:
        name = row.get("Name", "")
        req_count = int(row.get("Request Count", 0))
        fail_count = int(row.get("Failure Count", 0))
        med = float(row.get("Median Response Time", 0))
        p95 = float(row.get("95%", 0))
        p99 = float(row.get("99%", 0))
        rps = float(row.get("Requests/s", 0))
        fail_rate = (fail_count / req_count * 100) if req_count > 0 else 0.0

        if name == "Aggregated":
            total_row = row
            status = "PASS" if p95 < 250 and fail_rate < 1.0 else "REVIEW"
            print(f"-> {name}: {req_count} requests | {rps:.1f} RPS | Med: {med:.1f}ms | P95: {p95:.1f}ms | P99: {p99:.1f}ms | Fail: {fail_rate:.2f}% [{status}]")
        else:
            print(f"   {name:<24}: {req_count:>5} reqs | Med: {med:>5.1f}ms | P95: {p95:>5.1f}ms | RPS: {rps:>5.1f}")

    if total_row:
        p95_val = float(total_row.get("95%", 0))
        fail_val = float(total_row.get("Failure Count", 0)) / max(1, int(total_row.get("Request Count", 1))) * 100
        p95_target_met = p95_val < 250.0
        error_target_met = fail_val < 1.0

        tex_rows = []
        for r in stats:
            name = r.get("Name", "").replace("_", "\\_").replace("/", "\\/")
            reqs = r.get("Request Count", "0")
            med = f"{float(r.get('Median Response Time', 0)):.1f}"
            p95 = f"{float(r.get('95%', 0)):.1f}"
            p99 = f"{float(r.get('99%', 0)):.1f}"
            rps = f"{float(r.get('Requests/s', 0)):.1f}"
            fails = r.get("Failure Count", "0")
            tex_rows.append(f"    {name} & {reqs} & {rps} & {med} & {p95} & {p99} & {fails} \\\\")

        tex_content = f"""% Auto-generated by scripts/run_locust_evaluation.py
% Performance & Elasticity Evaluation Table for Section 4.3 of Preliminary.pdf
\\begin{{table}}[h]
\\centering
\\small
\\begin{{tabular}}{{lrrrrrr}}
\\hline
\\textbf{{Endpoint / Task}} & \\textbf{{Requests}} & \\textbf{{Throughput (RPS)}} & \\textbf{{Median (ms)}} & \\textbf{{P95 (ms)}} & \\textbf{{P99 (ms)}} & \\textbf{{Failures}} \\\\
\\hline
{os.linesep.join(tex_rows)}
\\hline
\\end{{tabular}}
\\caption{{Performance and Elasticity Evaluation Results under Concurrency ($P95 = {p95_val:.1f}$ ms vs Target $<250$ ms: {'\\textbf{{Met}}' if p95_target_met else 'Unmet'}; Error Rate $= {fail_val:.2f}\\%$ vs Target $<1\\%$: {'\\textbf{{Met}}' if error_target_met else 'Unmet'}).}}
\\label{{tab:locust_performance}}
\\end{{table}}
"""
        with open(OUTPUT_TEX, "w", encoding="utf-8") as f:
            f.write(tex_content)
        print(f"\nLaTeX performance table written to: {OUTPUT_TEX}")

if __name__ == "__main__":
    host = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
    stats = run_locust(host=host, users=40, spawn_rate=10, run_time="10s")
    process_results(stats)
